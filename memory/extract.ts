import { createHash, randomBytes } from 'node:crypto';
import { DegradedOutputError, type JsonRequest, type Model } from './ai.ts';
import type { MemoryStore } from './store.ts';
import type { MemoryRecipe, StoredRun } from './types.ts';
import type { RunRecord } from '../shared/types.ts';
import { isExternalTask, kindOf, recipeKind, upgradeKey } from './upgrade.ts';

type Lesson = { sameAsRecipeId: string | null; pitfalls: string };

type Extraction = {
  sameAsRecipeId: string | null;
  preconditions: string;
  steps: string;
  pitfalls: string;
  diffSketch: string;
};

const text = { type: 'string' };
const SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['sameAsRecipeId', 'preconditions', 'steps', 'pitfalls', 'diffSketch'],
  properties: {
    sameAsRecipeId: { type: ['string', 'null'] },
    preconditions: text,
    steps: text,
    pitfalls: text,
    diffSketch: text,
  },
};

const LESSON_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['sameAsRecipeId', 'pitfalls'],
  properties: { sameAsRecipeId: { type: ['string', 'null'] }, pitfalls: text },
};

const SYSTEM = `You distil a successful run into a recipe: advice a future engineer reads before handling a similar change in a DIFFERENT repository. The change may be an API change, or an upgrade forced from outside the code: a runtime or framework reaching end of life, a library major, a security fix, a retired AI model, a base image or a CI action version. The recipe is guidance, not a rule; they will adapt it to their code. A run succeeded if its checks verified it or a human merged or edited its PR.

You get the task, the agent's diff, the checks, the run's outcome, the agent's transcript and, when a human edited the PR, the human's final diff. Write:
- preconditions: what the code looks like when this recipe applies (SDK or dependency, the version it starts from, call shapes, where the version is declared).
- steps: what to do, in order. Generalise away repository-specific names (files, variables, business logic) but keep exact provider API names, parameters, versions, image tags, action versions and model ids. For an upgrade, list every kind of place the version had to move together (for example package.json engines, .nvmrc, Dockerfile FROM, the CI matrix, lockfiles regenerated by the package manager).
- pitfalls: what went wrong or nearly did, including every dead end the agent hit in the transcript and how it got out. When the human's final diff differs from the agent's, say what the human changed and why it was likely needed: that is the most valuable lesson.
- diffSketch: a short generic before/after diff of the core change, following the human's final diff when there is one.

You also get the recipes memory already holds for this provider or dependency. If this run applies the same technique as one of them, set sameAsRecipeId to its id and return merged, improved text for that recipe that keeps what was already true and adds what this run taught, including a new version range it covers. Otherwise set sameAsRecipeId to null.`;

const LESSON_SYSTEM = `You read a migration or upgrade run that did not succeed: it failed, needed review, or a human closed its PR. You never write a new recipe from it. You decide whether it teaches a pitfall for one of the recipes memory already holds for this provider.

If the run hit a dead end, a wrong assumption or a missed check that an engineer following one of those recipes should know about, set sameAsRecipeId to that recipe's id. Return that recipe's pitfalls with this run's lesson added, keeping what was already there, and say the lesson comes from a run that did not succeed. Otherwise set sameAsRecipeId to null and pitfalls to an empty string.`;

const MAX_TRANSCRIPT_CHARS = 600_000;

// A human merging or editing the PR is the strongest success signal; closing it outweighs passing checks.
export function succeeded({ outcome, humanVerdict }: RunRecord): boolean {
  if (humanVerdict === 'merged' || humanVerdict === 'edited') return true;
  return outcome === 'verified' && humanVerdict !== 'closed';
}

// A successful run becomes a new or merged recipe. Any other attempt can only add pitfalls to a recipe the
// model names. Returns the recipe it saved, if any; this never blocks a run.
export async function extractRecipe(
  run: StoredRun,
  deps: { store: MemoryStore; model: Model; now?: () => Date },
): Promise<MemoryRecipe | undefined> {
  const success = succeeded(run.record);
  if (!success && run.record.outcome === 'not-affected') return undefined;
  const { provider, kind } = run.task.change;
  const key = upgradeKey(run.task);
  // Candidates for the model to merge into: the same provider, or the same dependency for an upgrade.
  // Which one it is, if any, is the model's call.
  const existing = (await deps.store.listRecipes()).filter(
    (recipe) =>
      recipe.provider === provider ||
      (key !== undefined && recipe.upgrade?.dependency === key.dependency),
  );
  // A lesson from an unsuccessful run needs a recipe to attach to.
  if (!success && existing.length === 0) return undefined;

  const now = (deps.now?.() ?? new Date()).toISOString();
  const prompt = buildPrompt(run, existing);
  const humanDiffSha = run.humanDiff ? sha(run.humanDiff) : undefined;
  // Onto a fresh read of the run: a verdict can arrive while the model works.
  // shortcut: one landing between this read and write is still lost; a store with row locks closes it.
  const mark = async (extraction: StoredRun['extraction']) =>
    deps.store.saveRun({ ...((await deps.store.getRun(run.id)) ?? run), extraction });

  let result: Extraction | Lesson;
  try {
    result = success
      ? await ask<Extraction>(deps.model, { system: SYSTEM, prompt, schema: SCHEMA }, (r) =>
          (['preconditions', 'steps', 'pitfalls', 'diffSketch'] as const).filter(
            (field) => !r[field]?.trim(),
          ),
        )
      : await ask<Lesson>(
          deps.model,
          { system: LESSON_SYSTEM, prompt, schema: LESSON_SCHEMA },
          (r) => (r.sameAsRecipeId && !r.pitfalls?.trim() ? ['pitfalls'] : []),
        );
  } catch (error) {
    // Save nothing that could mislead later prompts; mark the run so it can be re-extracted.
    await mark({ status: 'failed', reason: String(error), at: now });
    throw error;
  }
  const { sameAsRecipeId, ...rest } = result;
  // A lesson may only change pitfalls, whatever else the model sends back.
  const guidance = success ? rest : { pitfalls: result.pitfalls };
  const same = existing.find((recipe) => recipe.id === sameAsRecipeId);

  let recipe: MemoryRecipe | undefined;
  if (same) {
    const { embedding: _staleEmbedding, ...kept } = same;
    // Only a successful run counts as another repo the recipe was verified on.
    const repos = success ? [...new Set([...same.repos, run.task.repo])] : same.repos;
    const ranges = success && key ? [...new Set([...(same.ranges ?? []), key.range])] : same.ranges;
    recipe = {
      ...kept,
      ...guidance,
      sourceRuns: [...new Set([...same.sourceRuns, run.id])],
      repos,
      verifiedRepos: repos.length,
      ...(ranges && { ranges }),
      ...(!same.upgrade && key && success && { upgrade: key }),
      updatedAt: now,
    };
  } else if (success) {
    const slug = (key?.dependency ?? provider).replace(/[^A-Za-z0-9_.-]/g, '-');
    recipe = {
      id: `recipe-${slug}-${kind}-${randomBytes(4).toString('hex')}`,
      provider,
      kind: recipeKind(kind),
      changeKind: kind,
      ...(key && { upgrade: key, ranges: [key.range] }),
      ...(guidance as Omit<Extraction, 'sameAsRecipeId'>),
      sourceRuns: [run.id],
      repos: [run.task.repo],
      verifiedRepos: 1,
      createdAt: now,
      updatedAt: now,
    };
  }
  if (recipe) await deps.store.saveRecipe(recipe);
  await mark({
    status: 'done',
    mode: success ? 'recipe' : 'pitfalls',
    ...(recipe && { recipeId: recipe.id }),
    at: now,
    ...(humanDiffSha && { humanDiffSha }),
  });
  return recipe;
}

// One retry when the answer comes back degraded; any other error goes straight up.
async function ask<T>(
  model: Model,
  request: JsonRequest,
  blankFields: (result: T) => string[],
): Promise<T> {
  for (let attempt = 1; ; attempt++) {
    try {
      const result = await model.json<T>(request);
      const blank = blankFields(result);
      if (blank.length) throw new DegradedOutputError(`Extraction left ${blank.join(', ')} blank`);
      return result;
    } catch (error) {
      if (!(error instanceof DegradedOutputError) || attempt === 2) throw error;
    }
  }
}

export function sha(text: string): string {
  return createHash('sha256').update(text).digest('hex').slice(0, 16);
}

function buildPrompt(run: StoredRun, existing: MemoryRecipe[]): string {
  const { change, usages } = run.task;
  const key = upgradeKey(run.task);
  const task = {
    provider: change.provider,
    kind: change.kind,
    title: change.title,
    effectiveDate: change.effectiveDate,
    source: change.source,
    affects: change.affects,
    usages,
    ...(isExternalTask(run.task) && {
      upgrade: key?.range,
      dependency: run.task.change.dependency,
      dependencyKind: run.task.change.dependencyKind,
      fromVersions: run.task.change.fromVersions,
      toVersion: run.task.change.toVersion,
      severity: run.task.change.severity,
      declaredIn: run.task.dependencies.map(({ name, version, declaredIn }) => ({
        name,
        version,
        declaredIn,
      })),
    }),
  };
  const { outcome: harnessOutcome, humanVerdict } = run.record;
  const human = run.humanDiff
    ? "A human edited the PR; their final diff is below the agent's."
    : "If a human edited the PR, only the agent's diff is shown, not theirs.";
  const outcome = `Harness outcome: ${harnessOutcome}. Human verdict on the PR: ${humanVerdict ?? 'none yet'}. ${human}`;
  const distilled =
    run.extraction?.status === 'done' && run.extraction.recipeId
      ? `\n\nThis run was already distilled into ${run.extraction.recipeId}. Set sameAsRecipeId to it and update it with what the human's edits teach, unless they show a different technique.`
      : '';
  const recipes = existing.map((recipe) => ({
    id: recipe.id,
    kind: kindOf(recipe),
    ...(recipe.ranges?.length && { ranges: recipe.ranges }),
    preconditions: recipe.preconditions,
    steps: recipe.steps,
    pitfalls: recipe.pitfalls,
  }));
  const subject = key ? `${change.provider} or ${key.dependency}` : change.provider;
  return [
    `## Task\n${JSON.stringify(task, null, 2)}`,
    `## Outcome\n${outcome}${distilled}`,
    `## Agent's diff\n${run.record.diff}`,
    ...(run.humanDiff ? [`## Human's final diff\n${run.humanDiff}`] : []),
    `## Checks (before -> after)\n${JSON.stringify(run.record.checks, null, 2)}`,
    `## Transcript\n${transcriptForPrompt(run.transcript)}`,
    `## Existing recipes for ${subject}\n${recipes.length ? JSON.stringify(recipes, null, 2) : 'None yet.'}`,
  ].join('\n\n');
}

// shortcut: keeps the head and tail of a huge transcript and drops the middle; summarise the middle with a cheap model pass if dead ends there get lost.
function transcriptForPrompt(transcript: string): string {
  if (transcript.length <= MAX_TRANSCRIPT_CHARS) return transcript;
  const half = MAX_TRANSCRIPT_CHARS / 2;
  const elided = transcript.length - MAX_TRANSCRIPT_CHARS;
  return `${transcript.slice(0, half)}\n\n[... ${elided} characters elided from the middle of this transcript; only its start and end are shown ...]\n\n${transcript.slice(-half)}`;
}
