import { readFileSync } from 'node:fs';
import ts from 'typescript-compiler';

// stripe-node 22.4.0 added `OtherString` to every open enum, so code typed against the known
// literals stops compiling after an upgrade across it. The repair restores exactly those literals
// with `Extract<…>`; on the old SDK each such type is unchanged, and runtime code never changes.
export const OPEN_ENUM_SINCE = '22.4.0';
export const OPEN_ENUM_RULE = 'stripe-open-enum';
// The validation repair stop reason that records this repair.
export const OPEN_ENUM_REPAIR = 'open-enum-repair';
// The stop reason when assertions at the sites of upgrade-introduced type errors made the checks pass.
export const TYPE_ASSERTION_REPAIR = 'type-assertion-repair';

// Generated by scripts/stripe-open-enums.mjs from the stripe@23.0.0 type declarations (2026-10-17).
const table = JSON.parse(
  readFileSync(new URL('./stripe-open-enums.json', import.meta.url), 'utf8'),
) as {
  enums: Record<string, string[]>;
  fields: Record<string, Record<string, { type: string; nullable: boolean }>>;
};
const { enums, fields } = table;

const parts = (version: string) => version.split('.').map(Number);
const below = (version: string, target: string) => {
  const [a, b] = [parts(version), parts(target)];
  for (let index = 0; index < 3; index++) if (a[index] !== b[index]) return a[index] < b[index];
  return false;
};
export const crossesOpenEnums = (from: string, to: string) =>
  below(from, OPEN_ENUM_SINCE) && !below(to, OPEN_ENUM_SINCE);

// stripe-node 13.0.0 dropped request properties from its types that no API version removed, so
// the contract diff never reports them. Stripe's API reference no longer lists them
// (https://docs.stripe.com/api/checkout/sessions/create.md?query=subscription_data, read
// 2026-10-24: `subscription_data` has `trial_end` and `trial_period_days`, no `trial_from_plan`).
// Checkout's `subscription_data.coupon` went in the same release but a version did remove it
// (https://docs.stripe.com/changelog/2022-08-01/removes-subscription-data-create-checkout-session,
// read 2026-10-24), so it is not listed. The restore keeps sending each property unchanged, spread
// from its own object literal so that the object's other properties are still checked, and the
// draft is [Needs review] with the check below.
// Owner decision (2026-10-24, Pierce, Push 279 decision 4): on by default.
export const KEEP_UNTYPED_REQUEST_PROPERTIES = true;
export const TYPE_REMOVALS_SINCE = '13.0.0';
export const UNTYPED_REQUEST_PROPERTIES = [
  {
    parent: 'subscription_data',
    property: 'trial_from_plan',
    type: 'SubscriptionData',
    reference: 'https://docs.stripe.com/api/checkout/sessions/create',
    // What the draft asks the reviewer to confirm (https://docs.stripe.com/payments/checkout/free-trials).
    check:
      'create a test-mode Checkout Session and check the subscription still starts with the trial, or send `subscription_data.trial_period_days` instead.',
  },
];
export const crossesTypeRemovals = (from: string, to: string) =>
  below(from, TYPE_REMOVALS_SINCE) && !below(to, TYPE_REMOVALS_SINCE);

// TypeScript 5.9 reports TS2353 on the property; the benchmark repositories' older releases
// report TS2322 at the same position.
export const untypedRequestProperty = (error: { code: string; message?: string }) =>
  ['TS2322', 'TS2353'].includes(error.code)
    ? UNTYPED_REQUEST_PROPERTIES.find(
        ({ property, type }) =>
          error.message?.includes(`'${property}' does not exist in type '${type}'`) ||
          ((error.message?.startsWith(`Type '{ ${property}: `) ||
            error.message?.includes(`; ${property}: `)) &&
            error.message.endsWith(` is not assignable to type '${type}'.`)),
      )
    : undefined;

interface Edit {
  start: number;
  end: number;
  replacement: string;
}
interface TypeErrorAt {
  file: string;
  line: number;
  column: number;
  code: string;
  message?: string;
}

const literals = (path: string) => enums[path].map((value) => `'${value}'`).join(' | ');

// Founders' decision (2026-10-27): a Stripe type the upgrade widened, assigned to a narrower type,
// gets an assertion to that type at the site, `(value as Target)`, which compiles to the same
// JavaScript. Only for an error whose message names both types, where the target is a type this
// file can write (literals, primitives and names it declares or imports) and the assertion drops no
// `null` or `undefined` the value's type has: a value Stripe now types as possibly missing stops.
// The caller keeps it only for errors the type oracle shows the upgrade introduced, and only when
// the repair passes the type-only gate (ai-patch-policies.ts typeOnlyRepairFailures).
const ASSIGNMENT =
  /^(?:Type|Argument of type) '(.+)' is not assignable to (?:type|parameter of type) '(.+)'\.$/;
const WRITABLE = new Set([
  ts.SyntaxKind.StringKeyword,
  ts.SyntaxKind.NumberKeyword,
  ts.SyntaxKind.BooleanKeyword,
  ts.SyntaxKind.BigIntKeyword,
  ts.SyntaxKind.UndefinedKeyword,
  ts.SyntaxKind.NullKeyword,
  ts.SyntaxKind.LiteralType,
  ts.SyntaxKind.UnionType,
  ts.SyntaxKind.ArrayType,
  ts.SyntaxKind.ParenthesizedType,
  ts.SyntaxKind.TypeReference,
  ts.SyntaxKind.StringLiteral,
  ts.SyntaxKind.NumericLiteral,
  ts.SyntaxKind.TrueKeyword,
  ts.SyntaxKind.FalseKeyword,
  ts.SyntaxKind.PrefixUnaryExpression,
]);
const parsedType = (text: string) => {
  const file = ts.createSourceFile('type.ts', `type T = ${text};`, ts.ScriptTarget.Latest, true);
  const [statement] = file.statements;
  return file.statements.length === 1 &&
    !(file as unknown as { parseDiagnostics: unknown[] }).parseDiagnostics.length &&
    ts.isTypeAliasDeclaration(statement)
    ? statement.type
    : undefined;
};
const missing = (type: ts.TypeNode) =>
  (ts.isUnionTypeNode(type) ? type.types : [type]).flatMap((member) =>
    member.kind === ts.SyntaxKind.UndefinedKeyword
      ? ['undefined']
      : ts.isLiteralTypeNode(member) && member.literal.kind === ts.SyntaxKind.NullKeyword
        ? ['null']
        : [],
  );
// Names declared or imported at the top of the file.
const fileNames = (source: ts.SourceFile) => {
  const names = new Set<string>();
  for (const statement of source.statements) {
    if (ts.isImportDeclaration(statement)) {
      const clause = statement.importClause;
      if (clause?.name) names.add(clause.name.text);
      const bindings = clause?.namedBindings;
      if (bindings && ts.isNamespaceImport(bindings)) names.add(bindings.name.text);
      else if (bindings) for (const element of bindings.elements) names.add(element.name.text);
    } else if (
      (ts.isInterfaceDeclaration(statement) ||
        ts.isTypeAliasDeclaration(statement) ||
        ts.isClassDeclaration(statement)) &&
      statement.name
    )
      names.add(statement.name.text);
  }
  return names;
};
function assertionSite(source: ts.SourceFile, node: ts.Node, position: number, error: TypeErrorAt) {
  const match = ['TS2322', 'TS2345'].includes(error.code) && ASSIGNMENT.exec(error.message ?? '');
  const value = match && parsedType(match[1]);
  const target = match && parsedType(match[2]);
  if (!match || !value || !target || match[2].includes('...')) return;
  const names = fileNames(source);
  let writable = true;
  const visit = (entry: ts.Node) => {
    if (ts.isTypeReferenceNode(entry)) {
      let name = entry.typeName;
      while (ts.isQualifiedName(name)) name = name.left;
      if (!names.has(name.text)) writable = false;
    }
    if (!WRITABLE.has(entry.kind) && !ts.isIdentifier(entry) && !ts.isQualifiedName(entry))
      writable = false;
    ts.forEachChild(entry, visit);
  };
  visit(target);
  const kept = new Set(missing(target));
  if (!writable || missing(value).some((type) => !kept.has(type))) return;
  // The value the error is about: a property's or variable's initializer, a returned or assigned
  // value, or an argument, each starting where the error does.
  let expression: ts.Expression | undefined;
  for (let current: ts.Node | undefined = node; current && !expression; current = current.parent) {
    if (
      (ts.isPropertyAssignment(current) || ts.isVariableDeclaration(current)) &&
      current.name.getStart(source) === position
    )
      expression = current.initializer;
    else if (ts.isReturnStatement(current) && current.getStart(source) === position)
      expression = current.expression;
    else if (
      ts.isBinaryExpression(current) &&
      current.operatorToken.kind === ts.SyntaxKind.EqualsToken &&
      current.left.getStart(source) === position
    )
      expression = current.right;
    else if (
      error.code === 'TS2345' &&
      ts.isCallExpression(current.parent ?? current) &&
      (current.parent as ts.CallExpression).arguments?.includes(current as ts.Expression) &&
      current.getStart(source) === position
    )
      expression = current as ts.Expression;
    if (ts.isStatement(current)) break;
  }
  return expression && { expression, type: match[2] };
}

// Returns the repaired files when every introduced error is one of the open-enum shapes this rule
// knows how to restore, or undefined when any error is something else.
export function openEnumRepair(
  files: { path: string; content: string }[],
  errors: TypeErrorAt[],
  keepUntyped = KEEP_UNTYPED_REQUEST_PROPERTIES,
  // Errors are repaired by a type assertion at their site (assertionSite) instead of the restores.
  assertions = false,
): { path: string; content: string }[] | undefined {
  if (!errors.length) return;
  const sources = new Map(
    files
      .filter((file) => /\.(?:[cm]?ts|tsx)$/.test(file.path) && !file.path.endsWith('.d.ts'))
      .map((file) => [
        file.path,
        ts.createSourceFile(file.path, file.content, ts.ScriptTarget.Latest, true),
      ]),
  );
  const edits = new Map<string, Edit[]>();
  const add = (file: ts.SourceFile, node: ts.Node, replacement: string) => {
    const list = edits.get(file.fileName) ?? [];
    const start = node.getStart(file);
    if (!list.some((edit) => edit.start === start && edit.end === node.getEnd()))
      list.push({ start, end: node.getEnd(), replacement });
    edits.set(file.fileName, list);
  };
  // The file's local name for the stripe default or namespace import.
  const namespaces = new Map<ts.SourceFile, string>();
  for (const source of sources.values())
    for (const statement of source.statements) {
      if (
        !ts.isImportDeclaration(statement) ||
        !ts.isStringLiteral(statement.moduleSpecifier) ||
        statement.moduleSpecifier.text !== 'stripe'
      )
        continue;
      const clause = statement.importClause;
      if (clause?.name) namespaces.set(source, clause.name.text);
      else if (clause?.namedBindings && ts.isNamespaceImport(clause.namedBindings))
        namespaces.set(source, clause.namedBindings.name.text);
    }
  // `Stripe.Price.Type` -> 'Price.Type' when the file imports stripe as `Stripe`.
  const sdkPath = (source: ts.SourceFile, name: ts.EntityName) => {
    const local = namespaces.get(source);
    const text = name.getText(source);
    return local && text.startsWith(`${local}.`) ? text.slice(local.length + 1) : undefined;
  };
  const enumReference = (source: ts.SourceFile, node: ts.TypeNode) =>
    ts.isTypeReferenceNode(node) && !node.typeArguments
      ? (() => {
          const path = sdkPath(source, node.typeName);
          return path && enums[path] ? path : undefined;
        })()
      : undefined;
  // The SDK interface a local identifier is annotated with in this file.
  const declaredInterface = (source: ts.SourceFile, identifier: ts.Identifier) => {
    let found: string | undefined;
    const visit = (node: ts.Node) => {
      if (
        (ts.isParameter(node) || ts.isVariableDeclaration(node)) &&
        ts.isIdentifier(node.name) &&
        node.name.text === identifier.text &&
        node.type &&
        ts.isTypeReferenceNode(node.type) &&
        node.pos <= identifier.pos
      ) {
        const path = sdkPath(source, node.type.typeName);
        if (path && fields[path]) found = path;
      }
      ts.forEachChild(node, visit);
    };
    visit(source);
    return found;
  };
  // `price.recurring?.interval` on a `Stripe.Price` -> the open enum and how its read is nullable.
  const enumRead = (source: ts.SourceFile, expression: ts.Expression) => {
    const names: string[] = [];
    let optional = false;
    let current = expression;
    while (ts.isPropertyAccessExpression(current) && ts.isIdentifier(current.name)) {
      names.unshift(current.name.text);
      if (current.questionDotToken) optional = true;
      current = current.expression;
    }
    if (!ts.isIdentifier(current) || !names.length) return;
    let owner = declaredInterface(source, current);
    let field: { type: string; nullable: boolean } | undefined;
    for (const name of names) {
      field = owner ? fields[owner]?.[name] : undefined;
      if (!field) return;
      owner = field.type;
    }
    if (!field || !enums[field.type]) return;
    return { path: field.type, nullable: field.nullable, optional };
  };
  const castRead = (source: ts.SourceFile, expression: ts.Expression) => {
    const read = enumRead(source, expression);
    if (!read) return false;
    const local = namespaces.get(source)!;
    add(
      source,
      expression,
      `(${expression.getText(source)} as Extract<${local}.${read.path}, ${literals(read.path)}>${read.nullable ? ' | null' : ''}${read.optional ? ' | undefined' : ''})`,
    );
    return true;
  };
  const castValue = (source: ts.SourceFile, value: ts.Expression): boolean => {
    let current = value;
    while (ts.isParenthesizedExpression(current)) current = current.expression;
    if (
      ts.isBinaryExpression(current) &&
      [ts.SyntaxKind.QuestionQuestionToken, ts.SyntaxKind.BarBarToken].includes(
        current.operatorToken.kind,
      )
    )
      return castValue(source, current.left);
    return castRead(source, current);
  };
  // Application interfaces and type aliases by name, for a variable annotated with one.
  const declarations = new Map<
    string,
    { source: ts.SourceFile; members: ts.NodeArray<ts.TypeElement> }[]
  >();
  for (const source of sources.values())
    for (const statement of source.statements) {
      const members = ts.isInterfaceDeclaration(statement)
        ? statement.members
        : ts.isTypeAliasDeclaration(statement) && ts.isTypeLiteralNode(statement.type)
          ? statement.type.members
          : undefined;
      if (!members) continue;
      const name = (statement as ts.InterfaceDeclaration | ts.TypeAliasDeclaration).name.text;
      declarations.set(name, [...(declarations.get(name) ?? []), { source, members }]);
    }
  // Narrows an application type's open-enum fields and casts the reads its literal assigns them.
  const narrowVariable = (source: ts.SourceFile, declaration: ts.VariableDeclaration) => {
    if (!declaration.type || !ts.isTypeReferenceNode(declaration.type)) return false;
    const owners = declarations.get(declaration.type.typeName.getText(source));
    if (owners?.length !== 1) return false;
    const { source: owner, members } = owners[0];
    let changed = false;
    for (const member of members) {
      if (!ts.isPropertySignature(member) || !member.type) continue;
      for (const type of ts.isUnionTypeNode(member.type) ? member.type.types : [member.type]) {
        const path = enumReference(owner, type);
        if (!path) continue;
        add(owner, type, `Extract<${type.getText(owner)}, ${literals(path)}>`);
        changed = true;
      }
    }
    if (!changed) return false;
    if (declaration.initializer && ts.isObjectLiteralExpression(declaration.initializer))
      for (const property of declaration.initializer.properties)
        if (ts.isPropertyAssignment(property)) castValue(source, property.initializer);
    return true;
  };
  const innermost = (source: ts.SourceFile, position: number) => {
    let found: ts.Node = source;
    const visit = (node: ts.Node) => {
      if (node.getStart(source) <= position && position < node.getEnd()) {
        found = node;
        ts.forEachChild(node, visit);
      }
    };
    ts.forEachChild(source, visit);
    return found;
  };
  const ancestor = <T extends ts.Node>(node: ts.Node, test: (node: ts.Node) => node is T) => {
    for (let current: ts.Node | undefined = node; current; current = current.parent)
      if (test(current)) return current;
  };
  for (const error of errors) {
    const source = sources.get(error.file);
    if (!source) return;
    const position = source.getPositionOfLineAndCharacter(error.line - 1, error.column - 1);
    const node = innermost(source, position);
    let repaired = false;
    const untyped = keepUntyped ? untypedRequestProperty(error) : undefined;
    if (untyped) {
      // The error sits on the property itself, inside the literal its parent property holds.
      const assignment = ancestor(node, ts.isPropertyAssignment);
      const owner = assignment?.parent.parent;
      if (
        assignment &&
        ts.isIdentifier(assignment.name) &&
        assignment.name.text === untyped.property &&
        assignment.name.getStart(source) === position &&
        owner &&
        ts.isPropertyAssignment(owner) &&
        ts.isIdentifier(owner.name) &&
        owner.name.text === untyped.parent
      ) {
        add(source, assignment, `...{ ${assignment.getText(source)} }`);
        repaired = true;
      }
    } else if (error.code === 'TS2538') {
      const access = ancestor(node, ts.isIndexedAccessTypeNode);
      const path = access && enumReference(source, access.indexType);
      if (access && path && ts.isTypeReferenceNode(access.objectType)) {
        add(
          source,
          access.indexType,
          `Extract<${access.indexType.getText(source)}, keyof ${access.objectType.getText(source)}>`,
        );
        repaired = true;
      }
    } else if (error.code === 'TS7053') {
      const access = ancestor(node, ts.isElementAccessExpression);
      const read = access && enumRead(source, access.argumentExpression);
      const object = access && ts.isIdentifier(access.expression) ? access.expression : undefined;
      const owner = object && declaredInterface(source, object);
      if (access && read && owner) {
        const local = namespaces.get(source)!;
        add(
          source,
          access.argumentExpression,
          `${access.argumentExpression.getText(source)} as Extract<${local}.${read.path}, keyof ${local}.${owner}>`,
        );
        repaired = true;
      }
    } else if (assertions && assertionSite(source, node, position, error)) {
      const { expression, type } = assertionSite(source, node, position, error)!;
      add(source, expression, `(${expression.getText(source)} as ${type})`);
      repaired = true;
    } else if (['TS2322', 'TS2345', 'TS2769'].includes(error.code)) {
      const property = ancestor(node, ts.isPropertyAssignment);
      // An error on a property is about that property's value; any other is about a variable
      // annotated with an application type whose open-enum fields the upgrade widened.
      if (property && property.name.getStart(source) === position)
        repaired = castValue(source, property.initializer);
      else {
        const statement = ancestor(node, (entry): entry is ts.Statement => ts.isStatement(entry));
        const visit = (entry: ts.Node) => {
          if (ts.isIdentifier(entry)) {
            const visitDeclaration = (candidate: ts.Node) => {
              if (
                ts.isVariableDeclaration(candidate) &&
                ts.isIdentifier(candidate.name) &&
                candidate.name.text === entry.text &&
                narrowVariable(source, candidate)
              )
                repaired = true;
              ts.forEachChild(candidate, visitDeclaration);
            };
            visitDeclaration(source);
          }
          ts.forEachChild(entry, visit);
        };
        if (statement) visit(statement);
      }
    }
    if (!repaired) return;
  }
  const results: { path: string; content: string }[] = [];
  for (const [path, list] of edits) {
    list.sort((a, b) => b.start - a.start);
    // Nested repairs would apply out of order; such a candidate is left to the other repairs.
    if (list.some((edit, index) => index > 0 && edit.end > list[index - 1].start)) return;
    let content = files.find((file) => file.path === path)!.content;
    for (const edit of list)
      content = content.slice(0, edit.start) + edit.replacement + content.slice(edit.end);
    results.push({ path, content });
  }
  return results;
}

// The introduced errors the restore handles, each on its own. Before an AI repair of a rules
// proposal, the restore applies to these and leaves the rest to the model.
export function restorableOpenEnumErrors<T extends TypeErrorAt>(
  files: { path: string; content: string }[],
  errors: T[],
  keepUntyped = KEEP_UNTYPED_REQUEST_PROPERTIES,
  assertions = false,
) {
  return errors.filter((error) => openEnumRepair(files, [error], keepUntyped, assertions));
}

// A restored candidate whose checks still fail is kept, as the AI repair's starting point, only
// when it fails on type errors and every one is an introduced error the restore did not target.
export function keepsPartialRestore(
  introduced: { key: string }[],
  restored: { key: string }[],
  remaining: { key: string }[],
) {
  const targeted = new Set(restored.map((error) => error.key));
  const left = new Set(
    introduced.filter((error) => !targeted.has(error.key)).map((error) => error.key),
  );
  return remaining.length > 0 && remaining.every((error) => left.has(error.key));
}
