import { expect, it } from 'vitest';
import { lockChangesOutside, lockedReleases } from './lockfile-graph.ts';

const NAMES = ['@shopify/shopify-app-remix', '@shopify/shopify-api', '@remix-run/node'];
const integrity = (seed: string) => `sha512-${seed.repeat(86).slice(0, 86)}==`;

function pnpm(remix: string, api: string, extra: { react?: string; polarisIsbot?: string } = {}) {
  const react = extra.react ?? '18.2.0';
  return `lockfileVersion: '9.0'

settings:
  autoInstallPeers: true
  excludeLinksFromLockfile: false

importers:

  .:
    dependencies:
      '@shopify/polaris':
        specifier: ^12.0.0
        version: 12.0.0(react@${react})
      '@shopify/shopify-app-remix':
        specifier: ^${remix}
        version: ${remix}(@remix-run/node@2.17.0)
      react:
        specifier: ^18.2.0
        version: ${react}

packages:

  '@remix-run/node@2.17.0':
    resolution: {integrity: ${integrity('n')}}

  '@shopify/polaris@12.0.0':
    resolution: {integrity: ${integrity('p')}}

  '@shopify/shopify-api@${api}':
    resolution: {integrity: ${integrity(api[0])}}

  '@shopify/shopify-app-remix@${remix}':
    resolution: {integrity: ${integrity(remix[0])}}

  isbot@5.1.0:
    resolution: {integrity: ${integrity('i')}}

${extra.polarisIsbot ? `  isbot@${extra.polarisIsbot}:\n    resolution: {integrity: ${integrity('j')}}\n` : ''}
  react@${react}:
    resolution: {integrity: ${integrity(react[1])}}

snapshots:

  '@remix-run/node@2.17.0': {}

  '@shopify/polaris@12.0.0(react@${react})':
    dependencies:
      isbot: ${extra.polarisIsbot ?? '5.1.0'}
      react: ${react}

  '@shopify/shopify-api@${api}': {}

  '@shopify/shopify-app-remix@${remix}(@remix-run/node@2.17.0)':
    dependencies:
      '@remix-run/node': 2.17.0
      '@shopify/shopify-api': ${api}
      isbot: 5.1.0

  isbot@5.1.0: {}

${extra.polarisIsbot ? `  isbot@${extra.polarisIsbot}: {}\n` : ''}
  react@${react}: {}
`;
}

const project = (lockfile: string, manifest: Record<string, unknown> = {}) => ({
  lockfile,
  manifests: { '.': manifest },
});

it('keeps a pnpm re-resolution only when nothing outside the named packages changes', () => {
  const before = project(pnpm('3.4.0', '11.14.1'));
  expect(lockChangesOutside('pnpm', before, project(pnpm('5.0.1', '14.0.1')), NAMES)).toEqual([]);
  // A package the root declares moves.
  expect(
    lockChangesOutside(
      'pnpm',
      before,
      project(pnpm('5.0.1', '14.0.1', { react: '18.3.1' })),
      NAMES,
    ),
  ).toContain('react@18.3.1');
  // A dependency of an unnamed package moves.
  expect(
    lockChangesOutside(
      'pnpm',
      before,
      project(pnpm('5.0.1', '14.0.1', { polarisIsbot: '5.2.0' })),
      NAMES,
    ),
  ).toEqual(expect.arrayContaining(['@shopify/polaris@12.0.0', 'isbot@5.2.0']));
  // The lockfile's own settings change.
  expect(
    lockChangesOutside(
      'pnpm',
      before,
      project(pnpm('5.0.1', '14.0.1').replace('autoInstallPeers: true', 'autoInstallPeers: false')),
      NAMES,
    ),
  ).toEqual(['the lockfile settings']);
  const releases = lockedReleases('pnpm', project(pnpm('5.0.1', '14.0.1')));
  expect(releases.root['@shopify/shopify-app-remix']).toBe('5.0.1');
  expect([...releases.all.get('@shopify/shopify-api')!]).toEqual(['14.0.1']);
});

function yarn(remix: string, api: string, react = '18.2.0') {
  return `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@shopify/shopify-api@^${api}":
  version "${api}"
  resolved "https://registry.yarnpkg.com/@shopify/shopify-api/-/shopify-api-${api}.tgz#a"
  integrity ${integrity(api[0])}

"@shopify/shopify-app-remix@^${remix}":
  version "${remix}"
  resolved "https://registry.yarnpkg.com/@shopify/shopify-app-remix/-/shopify-app-remix-${remix}.tgz#b"
  integrity ${integrity(remix[0])}
  dependencies:
    "@shopify/shopify-api" "^${api}"
    isbot "^5.1.0"

isbot@^5.1.0:
  version "5.1.0"
  resolved "https://registry.yarnpkg.com/isbot/-/isbot-5.1.0.tgz#c"
  integrity ${integrity('i')}

react@^18.2.0:
  version "${react}"
  resolved "https://registry.yarnpkg.com/react/-/react-${react}.tgz#d"
  integrity ${integrity(react[1])}
`;
}

it('compares Yarn 1 lockfiles through the declarations of each package.json', () => {
  const manifest = (remix: string) => ({
    dependencies: { '@shopify/shopify-app-remix': `^${remix}`, react: '^18.2.0' },
  });
  const before = project(yarn('3.4.0', '11.14.1'), manifest('3.4.0'));
  const after = project(yarn('5.0.1', '14.0.1'), manifest('5.0.1'));
  expect(lockChangesOutside('yarn', before, after, NAMES)).toEqual([]);
  expect(
    lockChangesOutside(
      'yarn',
      before,
      project(yarn('5.0.1', '14.0.1', '18.3.1'), manifest('5.0.1')),
      NAMES,
    ),
  ).toContain('react@18.3.1');
  expect(lockedReleases('yarn', after).root).toEqual({
    '@shopify/shopify-app-remix': '5.0.1',
    react: '18.2.0',
  });
});

function berry(api: string, react = '18.2.0') {
  return `__metadata:
  version: 8
  cacheKey: 10c0

"@shopify/shopify-api@npm:^${api}":
  version: ${api}
  resolution: "@shopify/shopify-api@npm:${api}"
  checksum: 10c0/${api[0].repeat(128)}
  languageName: node
  linkType: hard

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  dependencies:
    "@shopify/shopify-api": "npm:^${api}"
    react: "npm:^18.2.0"
  languageName: unknown
  linkType: soft

"react@npm:^18.2.0":
  version: ${react}
  resolution: "react@npm:${react}"
  checksum: 10c0/${react[1].repeat(128)}
  languageName: node
  linkType: hard
`;
}

it('compares Yarn Berry lockfiles through their workspace entries', () => {
  const before = project(berry('11.14.1'));
  expect(lockChangesOutside('yarn-berry', before, project(berry('14.0.1')), NAMES)).toEqual([]);
  expect(
    lockChangesOutside('yarn-berry', before, project(berry('14.0.1', '18.3.1')), NAMES),
  ).toContain('react@npm:18.3.1');
  expect(
    lockChangesOutside(
      'yarn-berry',
      before,
      project(berry('14.0.1').replace('cacheKey: 10c0', 'cacheKey: 9')),
      NAMES,
    ),
  ).toEqual(['the lockfile settings']);
  expect(lockedReleases('yarn-berry', project(berry('14.0.1'))).root['@shopify/shopify-api']).toBe(
    '14.0.1',
  );
});
